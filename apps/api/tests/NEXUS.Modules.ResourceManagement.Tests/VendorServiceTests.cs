        context.Resources.Add(new Domain.Resource
        {
            Name = "Vendor Engineer",
            Type = "VendorResource",
            Status = "Active",
            VendorId = created.Value!.Id,
            IsActive = true
        });
        context.Resources.Add(new Domain.Resource
        {
            Name = "Vendor Designer",
            Type = "VendorResource",
            Status = "Active",
            VendorId = created.Value.Id,
            IsActive = true
        });
        await context.SaveChangesAsync();

        var result = await service.DeleteAsync(created.Value.Id, userId);


    [Fact]
    public async Task Create_SequentialCreates_StampTenantAndKeepCodesUnique()
    {
        // Regression: vendors were saved with TenantId == Guid.Empty, so the
        // tenant-scoped max-code query never saw them and every second create
        // collided on the (TenantId, Code) unique index with a misleading
        // "code generation conflicted" error.
        using var context = CreateContext();
        SeedVendorCategories(context);
        var service = CreateService(context);
        var userId = "11111111-1111-1111-1111-111111111111";

        var first = await service.CreateAsync(NewVendorDto(ActiveCategoryId), userId);
        var secondDto = NewVendorDto(ActiveCategoryId);
        secondDto.Name = "Second Vendor";
        var second = await service.CreateAsync(secondDto, userId);

        first.IsSuccess.Should().BeTrue();
        second.IsSuccess.Should().BeTrue();
        first.Value!.Code.Should().NotBe(second.Value!.Code);

        var createdIds = new[] { first.Value.Id, second.Value.Id };
        var persisted = await context.Vendors.AsNoTracking()
            .Where(v => createdIds.Contains(v.Id))
            .ToListAsync();
        persisted.Should().HaveCount(2);
        persisted.Should().OnlyContain(v => v.TenantId != Guid.Empty);
    }


    [Fact]
    public async Task Deactivate_KeepsVendorVisibleWithInactiveStatus()
    {
        using var context = CreateContext();
        SeedVendorCategories(context);
        var service = CreateService(context);
        var userId = "11111111-1111-1111-1111-111111111111";

        var created = await service.CreateAsync(NewVendorDto(ActiveCategoryId), userId);
        created.IsSuccess.Should().BeTrue();

        var deactivated = await service.DeactivateAsync(created.Value!.Id, userId);
        deactivated.IsSuccess.Should().BeTrue();

        result.Error.Message.Should().Contain("2 outsourced resources");
        result.Error.Message.Should().Contain("Deactivate");

        var stillThere = await service.GetByIdAsync(created.Value.Id);
        stillThere.IsSuccess.Should().BeTrue();
    }


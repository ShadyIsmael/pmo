        activeOnly.Items.Should().NotContain(v => v.Id == created.Value.Id);

        var inactiveOnly = await service.GetPagedAsync(1, 50, isActive: false);
        inactiveOnly.Items.Should().ContainSingle(v => v.Id == created.Value.Id);
    }

